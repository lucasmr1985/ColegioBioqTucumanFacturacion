
package ClienteSwissMedicalApi;


public class Cancelacion {
    private String creden;
    private String alta;
    private String ticketExt;
    private String param1;
     private String termId;
    private String codPrestador;

    public Cancelacion() {
    }

    public String getCreden() {
        return creden;
    }

    public void setCreden(String creden) {
        this.creden = creden;
    }

    public String getAlta() {
        return alta;
    }

    public void setAlta(String alta) {
        this.alta = alta;
    }

    public String getTicketExt() {
        return ticketExt;
    }

    public void setTicketExt(String ticketExt) {
        this.ticketExt = ticketExt;
    }

    public String getParam1() {
        return param1;
    }

    public void setParam1(String param1) {
        this.param1 = param1;
    }

    public String getTermId() {
        return termId;
    }

    public void setTermId(String termId) {
        this.termId = termId;
    }

    public String getCodPrestador() {
        return codPrestador;
    }

    public void setCodPrestador(String codPrestador) {
        this.codPrestador = codPrestador;
    }
    
}
