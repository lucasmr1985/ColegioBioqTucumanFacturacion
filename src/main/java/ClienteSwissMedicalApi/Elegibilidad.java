
package ClienteSwissMedicalApi;

public class Elegibilidad {
    private String creden;
    private String alta;
    private String fecdif;

    public Elegibilidad() {
    }

    public String getCreden() {
        return creden;
    }

    public void setCreden(String creden) {
        this.creden = creden;
    }

    public String getAlta() {
        return alta;
    }

    public void setAlta(String alta) {
        this.alta = alta;
    }

    public String getFecdif() {
        return fecdif;
    }

    public void setFecdif(String fecdif) {
        this.fecdif = fecdif;
    }
    
}
